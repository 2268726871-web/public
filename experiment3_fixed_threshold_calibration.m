%% experiment3_fixed_threshold_reselection.m
% 固定事件触发阈值重新筛选
%
% 功能：
% 1. 读取原阈值扫描结果；
% 2. 区分“绝对安全”和“没有新增越界”；
% 3. 确定当前条件下的初步固定阈值；
% 4. 判断该阈值能否作为论文最终阈值；
% 5. 输出更新后的表格和中文结果图。
%
% 数值性质：
% [D] thetaStab：理论稳定性分析得到的派生值；
% [A] 1%跟踪误差容差：算法设计值；
% [A] 初步固定阈值：仿真标定得到的算法设计值；
% [P] 设备参数：尚需依据实际设备规格核对。

clear;
clc;
close all;
format long g;

%% 1. 确定文件位置

codeDirectory = fileparts(mfilename('fullpath'));

resultDirectory = fullfile( ...
    codeDirectory, ...
    'results', ...
    'experiment3_fixed_threshold_calibration');

scanFile = fullfile( ...
    resultDirectory, ...
    'fixed_threshold_scan.csv');

periodicFile = fullfile( ...
    resultDirectory, ...
    'periodic_baseline_summary.csv');

assert(isfile(scanFile), ...
    ['未找到固定阈值扫描结果：\n%s\n', ...
     '请先运行原固定阈值标定程序。'], ...
    scanFile);

assert(isfile(periodicFile), ...
    ['未找到周期通信基准结果：\n%s\n', ...
     '请先运行原固定阈值标定程序。'], ...
    periodicFile);

%% 2. 读取已有仿真结果

scanTable = readtable(scanFile);

periodicTable = readtable(periodicFile);

requiredVariables = { ...
    'ThetaFraction', ...
    'ThetaF', ...
    'ThetaStab', ...
    'TrackingDegradation_pct', ...
    'CommunicationSaving_pct', ...
    'NetworkTransmissions', ...
    'SafetyViolationSamples', ...
    'InterlockConflicts', ...
    'WithinTrackingTolerance', ...
    'InsideStabilityBound', ...
    'NoInterlockConflict'};

missingVariables = setdiff( ...
    requiredVariables, ...
    scanTable.Properties.VariableNames);

assert(isempty(missingVariables), ...
    '扫描结果表缺少字段：%s', ...
    strjoin(missingVariables,', '));

assert(ismember( ...
    'SafetyViolationSamples', ...
    periodicTable.Properties.VariableNames), ...
    '周期通信结果中缺少SafetyViolationSamples字段。');

%% 3. 读取周期通信基准越界次数

periodicSafetyViolations = ...
    periodicTable.SafetyViolationSamples(1);

thetaStab = scanTable.ThetaStab(1);

trackingTolerance_pct = 1.0;       % [A]

fprintf('\n');
fprintf('====================================================\n');
fprintf('固定事件触发阈值重新筛选开始\n');
fprintf('====================================================\n');

fprintf('周期通信安全越界样本数 = %d\n', ...
    periodicSafetyViolations);

fprintf('理论稳定上界 thetaStab = %.15g\n', ...
    thetaStab);

fprintf('跟踪误差允许增幅 = %.2f%%\n', ...
    trackingTolerance_pct);

%% 4. 重新定义安全筛选条件

% 条件一：固定事件触发系统完全没有发生安全越界。
scanTable.AbsoluteSafetyPass = ...
    scanTable.SafetyViolationSamples == 0;

% 条件二：固定事件触发没有比周期通信增加安全越界。
scanTable.NoAdditionalSafetyViolation = ...
    scanTable.SafetyViolationSamples ...
    <= periodicSafetyViolations;

% 再次明确跟踪误差是否满足1%容差。
scanTable.WithinTrackingTolerance = ...
    scanTable.TrackingDegradation_pct ...
    <= trackingTolerance_pct;

% 再次明确阈值是否处于理论稳定范围。
scanTable.InsideStabilityBound = ...
    scanTable.ThetaF < scanTable.ThetaStab;

% 再次明确是否不存在设备互锁冲突。
scanTable.NoInterlockConflict = ...
    scanTable.InterlockConflicts == 0;

%% 5. 建立两级合格标准

% 第一级：用于当前固定阈值的初步标定。
%
% 允许继承周期通信基准原有的安全越界，
% 但不允许固定事件触发增加新的安全越界。
scanTable.QualifiedForCalibration = ...
    scanTable.WithinTrackingTolerance ...
    & scanTable.NoAdditionalSafetyViolation ...
    & scanTable.InsideStabilityBound ...
    & scanTable.NoInterlockConflict;

% 第二级：用于论文最终固定阈值。
%
% 除满足初步标定条件外，
% 还必须在72 h内完全没有安全越界。
scanTable.QualifiedForFinalSafeUse = ...
    scanTable.QualifiedForCalibration ...
    & scanTable.AbsoluteSafetyPass;

% 保留兼容字段。
scanTable.Qualified = ...
    scanTable.QualifiedForCalibration;

%% 6. 选择初步固定阈值

calibrationIndex = find( ...
    scanTable.QualifiedForCalibration);

if isempty(calibrationIndex)

    provisionalIndex = NaN;
    thetaProvisional = NaN;

else

    % 首先选择通信节省率最大的候选阈值。
    communicationSaving = ...
        scanTable.CommunicationSaving_pct( ...
        calibrationIndex);

    maximumSaving = max(communicationSaving);

    tiedIndex = calibrationIndex( ...
        abs(communicationSaving ...
        - maximumSaving) < 1e-12);

    % 如果通信节省率相同，
    % 选择跟踪误差增幅较小的候选值。
    degradation = ...
        scanTable.TrackingDegradation_pct( ...
        tiedIndex);

    minimumDegradation = min(degradation);

    tiedIndex2 = tiedIndex( ...
        abs(degradation ...
        - minimumDegradation) < 1e-12);

    % 如果仍然相同，则选择较小阈值，
    % 保留更大的理论稳定裕度。
    [~,localIndex] = min( ...
        scanTable.ThetaF(tiedIndex2));

    provisionalIndex = ...
        tiedIndex2(localIndex);

    thetaProvisional = ...
        scanTable.ThetaF(provisionalIndex);
end

scanTable.ProvisionalRecommended = ...
    false(height(scanTable),1);

if isfinite(provisionalIndex)

    scanTable.ProvisionalRecommended( ...
        provisionalIndex) = true;

end

%% 7. 检查是否存在最终安全阈值

finalIndexSet = find( ...
    scanTable.QualifiedForFinalSafeUse);

if isempty(finalIndexSet)

    finalIndex = NaN;
    thetaFinal = NaN;

else

    finalSaving = ...
        scanTable.CommunicationSaving_pct( ...
        finalIndexSet);

    maximumFinalSaving = max(finalSaving);

    finalTiedIndex = finalIndexSet( ...
        abs(finalSaving ...
        - maximumFinalSaving) < 1e-12);

    finalDegradation = ...
        scanTable.TrackingDegradation_pct( ...
        finalTiedIndex);

    minimumFinalDegradation = ...
        min(finalDegradation);

    finalTiedIndex2 = finalTiedIndex( ...
        abs(finalDegradation ...
        - minimumFinalDegradation) < 1e-12);

    [~,localFinalIndex] = min( ...
        scanTable.ThetaF(finalTiedIndex2));

    finalIndex = ...
        finalTiedIndex2(localFinalIndex);

    thetaFinal = ...
        scanTable.ThetaF(finalIndex);
end

scanTable.FinalRecommended = ...
    false(height(scanTable),1);

if isfinite(finalIndex)

    scanTable.FinalRecommended(finalIndex) = true;

end

%% 8. 保存重新筛选后的结果

recheckedScanFile = fullfile( ...
    resultDirectory, ...
    'fixed_threshold_scan_rechecked.csv');

writetable(scanTable,recheckedScanFile);

if isfinite(provisionalIndex)

    provisionalTable = ...
        scanTable(provisionalIndex,:);

    writetable( ...
        provisionalTable, ...
        fullfile( ...
        resultDirectory, ...
        'provisional_fixed_threshold.csv'));
end

if isfinite(finalIndex)

    finalTable = ...
        scanTable(finalIndex,:);

    writetable( ...
        finalTable, ...
        fullfile( ...
        resultDirectory, ...
        'final_fixed_threshold.csv'));
end

save( ...
    fullfile( ...
        resultDirectory, ...
        'fixed_threshold_reselection.mat'), ...
    'scanTable', ...
    'periodicTable', ...
    'periodicSafetyViolations', ...
    'thetaStab', ...
    'trackingTolerance_pct', ...
    'provisionalIndex', ...
    'thetaProvisional', ...
    'finalIndex', ...
    'thetaFinal');

%% 9. 绘制重新筛选结果

figure( ...
    'Color','w', ...
    'Name','固定阈值重新筛选结果', ...
    'Position',[100 100 1050 620]);

yyaxis left

trackingLine = plot( ...
    scanTable.ThetaF, ...
    scanTable.TrackingDegradation_pct, ...
    '-o', ...
    'LineWidth',1.6, ...
    'MarkerSize',5, ...
    'Color',[0 0.4470 0.7410]);

hold on;

toleranceLine = yline( ...
    trackingTolerance_pct, ...
    '--', ...
    '跟踪误差容差1%', ...
    'LineWidth',1.3, ...
    'Color',[0.85 0.1 0.1]);

ylabel('综合跟踪误差增幅/%');

yyaxis right

savingLine = plot( ...
    scanTable.ThetaF, ...
    scanTable.CommunicationSaving_pct, ...
    '-s', ...
    'LineWidth',1.6, ...
    'MarkerSize',5, ...
    'Color',[0.8500 0.3250 0.0980]);

ylabel('通信节省率/%');

if isfinite(provisionalIndex)

    provisionalPoint = scatter( ...
        thetaProvisional, ...
        scanTable.CommunicationSaving_pct( ...
        provisionalIndex), ...
        100, ...
        [0.1 0.65 0.2], ...
        'filled', ...
        'MarkerEdgeColor','k');

    text( ...
        thetaProvisional, ...
        scanTable.CommunicationSaving_pct( ...
        provisionalIndex), ...
        sprintf(['  初步阈值\\n', ...
        '  \\theta_f=%.4f'], ...
        thetaProvisional), ...
        'FontSize',10, ...
        'Color',[0 0.45 0]);
else
    provisionalPoint = [];
end

stabilityLine = xline( ...
    thetaStab, ...
    ':', ...
    '理论稳定上界', ...
    'LineWidth',1.5, ...
    'Color',[0.25 0.25 0.25]);

grid on;
box on;

xlabel('固定事件触发阈值 \theta_f');

title('固定阈值对控制性能与通信节省的影响');

if isempty(provisionalPoint)

    legend( ...
        [trackingLine,toleranceLine, ...
         savingLine,stabilityLine], ...
        {'跟踪误差增幅', ...
         '1%跟踪误差容差', ...
         '通信节省率', ...
         '理论稳定上界'}, ...
        'Location','best');

else

    legend( ...
        [trackingLine,toleranceLine, ...
         savingLine,provisionalPoint, ...
         stabilityLine], ...
        {'跟踪误差增幅', ...
         '1%跟踪误差容差', ...
         '通信节省率', ...
         '初步推荐阈值', ...
         '理论稳定上界'}, ...
        'Location','best');
end

exportgraphics( ...
    gcf, ...
    fullfile( ...
        resultDirectory, ...
        '图3_固定阈值重新筛选结果.png'), ...
    'Resolution',300);

%% 10. 输出结论

fprintf('\n');
fprintf('====================================================\n');
fprintf('固定事件触发阈值重新筛选完成\n');
fprintf('====================================================\n');

if isfinite(thetaProvisional)

    fprintf('\n得到初步固定阈值：\n');

    fprintf('thetaProvisional = %.15g\n', ...
        thetaProvisional);

    fprintf('占理论稳定上界比例 = %.2f%%\n', ...
        100*thetaProvisional/thetaStab);

    fprintf('跟踪误差增幅 = %.6f%%\n', ...
        scanTable.TrackingDegradation_pct( ...
        provisionalIndex));

    fprintf('通信节省率 = %.6f%%\n', ...
        scanTable.CommunicationSaving_pct( ...
        provisionalIndex));

    fprintf('全网发送次数 = %d\n', ...
        scanTable.NetworkTransmissions( ...
        provisionalIndex));

    fprintf('安全越界样本数 = %d\n', ...
        scanTable.SafetyViolationSamples( ...
        provisionalIndex));

    fprintf('互锁冲突数 = %d\n', ...
        scanTable.InterlockConflicts( ...
        provisionalIndex));

    fprintf('\n当前可临时记录为：\n');
    fprintf( ...
        'cfg.fixed.thetaProvisional = %.15g;\n', ...
        thetaProvisional);

else

    fprintf('\n没有得到初步固定阈值。\n');
    fprintf('需要检查跟踪误差、稳定上界或互锁条件。\n');

end

if isfinite(thetaFinal)

    fprintf('\n得到最终安全固定阈值：\n');
    fprintf('cfg.fixed.theta = %.15g;\n', ...
        thetaFinal);

else

    fprintf('\n尚未得到论文最终安全阈值。\n');

    fprintf(['原因：周期通信基准自身存在%d个', ...
        '安全越界样本。\n'], ...
        periodicSafetyViolations);

    fprintf(['在完成除湿设备参数核对并消除', ...
        '基准越界前，\n']);

    fprintf('cfg.fixed.theta必须继续保持NaN。\n');
end

fprintf('\n重新筛选结果保存在：\n%s\n', ...
    resultDirectory);

fprintf('====================================================\n');

disp(scanTable);