function selectedIndex = ...
    choose_best_threshold(scanTable,candidateIndex)

% 第一优先：通信节省率最大
saving = ...
    scanTable.CommunicationSaving_pct( ...
    candidateIndex);

maximumSaving = max(saving);

tie = candidateIndex( ...
    abs(saving-maximumSaving)<1e-12);

% 第二优先：跟踪误差增幅最小
degradation = ...
    scanTable.TrackingDegradation_pct(tie);

minimumDegradation = ...
    min(degradation);

tie2 = tie( ...
    abs(degradation-minimumDegradation)<1e-12);

% 第三优先：选择较小的阈值
[~,localIndex] = ...
    min(scanTable.ThetaF(tie2));

selectedIndex = ...
    tie2(localIndex);

end

