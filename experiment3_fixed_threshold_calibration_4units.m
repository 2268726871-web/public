    periodic, ...
    selected, ...
    clock, ...
    cfg, ...
    thetaStab, ...
    trackingTolerance_pct);

%% 13. 命令行显示结论

fprintf('\n====================================================\n');
fprintf('4台除湿器条件下的固定阈值标定完成\n');
fprintf('====================================================\n');

disp(scanTable);

if isfinite(selectedIndex)

