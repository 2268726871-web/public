function z = normalized_state(Trow,wrow,crow,model)

nRoom = numel(model.roomStage);

z = zeros(nRoom,3);

for i = 1:nRoom

    g = model.roomStage(i);

    Cppm = mass_to_ppm( ...
        crow(i), ...
        Trow(i), ...
        model.par.PIndoorRef_Pa, ...
        model.par);

    z(i,:) = [ ...
        (Trow(i)-model.T0(g)) ...
        /model.scaleT(g), ...
