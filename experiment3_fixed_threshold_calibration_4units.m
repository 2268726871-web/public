function w = humidity_ratio_from_t_rh_p( ...
    TdegC,RH_pct,P_Pa)

Tk = TdegC+273.15;

lnPws = zeros(size(TdegC));

above = TdegC>=0;

lnPws(above) = ...
    -5.8002206e3./Tk(above) ...
    +1.3914993 ...
    -4.8640239e-2.*Tk(above) ...
    +4.1764768e-5.*Tk(above).^2 ...
    -1.4452093e-8.*Tk(above).^3 ...
    +6.5459673.*log(Tk(above));

below = ~above;

lnPws(below) = ...
    -5.6745359e3./Tk(below) ...
    +6.3925247 ...
    -9.677843e-3.*Tk(below) ...
    +6.2215701e-7.*Tk(below).^2 ...
    +2.0747825e-9.*Tk(below).^3 ...
    -9.484024e-13.*Tk(below).^4 ...
    +4.1635019.*log(Tk(below));

Pws = exp(lnPws);

Pv = ...
    (RH_pct/100).*Pws;

w = ...
    0.621945*Pv ...
    ./(P_Pa-Pv);

end

%% ========================================================================
function c = ppm_to_mass( ...
    Cppm,TdegC,pressurePa,physical)

c = ...
    Cppm.*1e-6 ...
    .*pressurePa ...
    .*physical.MCO2_kg_mol ...
    ./(physical.R_J_molK ...
    .*(TdegC+273.15));

end

%% ========================================================================
function Cppm = mass_to_ppm( ...
    c,TdegC,pressurePa,physical)

Cppm = ...
    c ...
    .*physical.R_J_molK ...
    .*(TdegC+273.15) ...
    ./(pressurePa ...
    .*physical.MCO2_kg_mol) ...
    .*1e6;

end

