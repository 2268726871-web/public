%% ========================================================================
function [uRaw,uApplied,sat] = ...
    controller_step(zHat,model,out)

% 协同状态误差
etaHat = ...
    zHat ...
    +model.gamma ...
    *(model.L*zHat);

% 当前气象下的平衡输入
uFF = equilibrium_feedforward( ...
    model, ...
    out);

nRoom = numel(model.roomStage);

uRaw = zeros(nRoom,3);

for i = 1:nRoom

    g = model.roomStage(i);

    % 平衡输入 + 反馈修正
    uRaw(i,:) = ...
        uFF(g,:) ...
        +(model.H(:,:,g) ...
        *etaHat(i,:)')';

end

uApplied = uRaw;

% 制冷/加热上下限
uApplied(:,1) = min( ...
    max( ...
    uRaw(:,1), ...
    model.limits.QMin), ...
    model.limits.QMax);

% 加湿/除湿上下限
uApplied(:,2) = min( ...
    max( ...
    uRaw(:,2), ...
    model.limits.mwMin), ...
    model.limits.mwMax);

% 通风上下限
uApplied(:,3) = min( ...
    max( ...
    uRaw(:,3), ...
    model.limits.FMin), ...
    model.limits.FMax);

sat = [ ...
    uRaw(:,1)<model.limits.QMin, ...
    uRaw(:,1)>model.limits.QMax, ...
    uRaw(:,2)<model.limits.mwMin, ...
    uRaw(:,2)>model.limits.mwMax, ...
    uRaw(:,3)<model.limits.FMin, ...
    uRaw(:,3)>model.limits.FMax];

end

%% ========================================================================
function uFF = equilibrium_feedforward(model,out)

nStage = numel(model.T0);

cTarget = zeros(nStage,1);

for g = 1:nStage

    cTarget(g) = ppm_to_mass( ...
        model.Cppm0(g), ...
        model.T0(g), ...
        model.par.PIndoorRef_Pa, ...
        model.par);

end

% CO2平衡通风量
F0 = ...
    model.mbioC ...
    ./(cTarget-out.c);

% 水分平衡输入
mw0 = ...
    model.par.rhoAir_kg_m3 ...
    .*F0 ...
    .*(model.w0-out.w) ...
    -model.mbioW;

% 温度平衡输入
Q0 = ( ...
    model.par.UA_W_K ...
    +model.par.rhoAir_kg_m3 ...
    *model.par.cpAir_J_kgK ...
    .*F0) ...
    .*(model.T0-out.T) ...
    -model.Qbio;

uFF = [Q0,mw0,F0];

end

%% ========================================================================
function dx = room_rhs(x,u,bio,Mda,out,par)

T = x(1);
w = x(2);
c = x(3);

Q = u(1);
mw = u(2);
F = u(3);

dT = ( ...
    par.UA_W_K*(out.T-T) ...
    +par.rhoAir_kg_m3 ...
    *par.cpAir_J_kgK ...
    *F*(out.T-T) ...
    +Q ...
    +bio(1)) ...
    /par.CT_J_K;

dw = ( ...
    par.rhoAir_kg_m3 ...
    *F*(out.w-w) ...
    +mw ...
    +bio(2)) ...
    /Mda;

dc = ( ...
    F*(out.c-c) ...
    +bio(3)) ...
    /par.V_m3;

dx = [dT;dw;dc];

end

