function experiment3_fixed_threshold_calibration_4units
% 每仓4台除湿器条件下的固定事件触发阈值重新标定

clc;
close all;
format long g;

%% 1. 路径和参数入口

codeDir = fileparts(mfilename('fullpath'));

resultDir = fullfile( ...
    fileparts(mfilename('fullpath')), ...
    'results', ...
    'experiment3_fixed_threshold_4units_gamma035');

if ~exist(resultDir,'dir')
    mkdir(resultDir);
end

cfg = mushroom_system_parameters();

assert(cfg.device.nDehumidifier==4, ...
    ['当前参数入口不是每仓4台除湿器。', ...
     '请先把cfg.device.nDehumidifier修改为4并保存。']);

assert(abs(cfg.device.dehPerUnit_kg_h-0.8375)<1e-12, ...
    '单台除湿能力已经变化，请先核对设备参数来源。');

assert(abs(cfg.control.gamma-0.35)<1e-12, ...
    '协同增益必须使用实验二确定的0.35。');

assert(abs(cfg.initial.w_kg_kgda(2)-0.0165089)<1e-12, ...
    '2号仓初始含湿量必须为0.0165089。');

matrixDir = fullfile( ...
    codeDir, ...
    'results', ...
    'full_precision_matrices');

gainFile = fullfile( ...
    matrixDir, ...
    'feedback_gains.mat');

stabilityFile = fullfile( ...
    matrixDir, ...
    'fixed_event_stability_bound.mat');

assert(isfile(gainFile), ...
    ['找不到feedback_gains.mat，', ...
     '请先运行build_feedback_gains。']);

assert(isfile(stabilityFile), ...
    ['找不到fixed_event_stability_bound.mat，', ...
     '请先运行compute_fixed_event_stability_bound。']);

gainData = load(gainFile,'gain');

stabilityData = load( ...
    stabilityFile, ...
    'fixedStability');

assert( ...
    isfield(gainData,'gain') && ...
    isfield(gainData.gain,'H'), ...
    'feedback_gains.mat中缺少gain.H。');

assert( ...
    isfield(stabilityData,'fixedStability') && ...
    isfield(stabilityData.fixedStability,'thetaStab'), ...
    '稳定性结果中缺少fixedStability.thetaStab。');

H = gainData.gain.H;

thetaStab = ...
    stabilityData.fixedStability.thetaStab;

assert( ...
    isequal(size(H),[3 3 4]) && ...
    all(isfinite(H(:))), ...
    '反馈增益H的尺寸或数值不正确。');

assert( ...
    isfinite(thetaStab) && thetaStab>0, ...
    'thetaStab必须是正的有限数。');

%% 2. 固定阈值候选和筛选规则

% 阈值取理论稳定上界的5%至90%
% 相邻候选间隔为理论上界的2.5%
thetaFraction = (0.05:0.025:0.90)';

thetaCandidates = ...
    thetaFraction*thetaStab;

% 综合跟踪误差允许增幅
trackingTolerance_pct = 1.0;

% 用于排除浮点零误触发
eventNumericalTolerance = 1e-12;

assert( ...
    all(thetaCandidates>0 & ...
    thetaCandidates<thetaStab), ...
    '存在超出理论稳定范围的候选阈值。');

%% 3. 时间设置

dt = cfg.time.dt_s;

controlPeriod = ...
    cfg.time.controlPeriod_s;

eventPeriod = ...
    cfg.time.eventCheckPeriod_s;

weatherPeriod = ...
    cfg.time.weatherPeriod_s;

tEnd = ...
    cfg.time.mainDuration_s;

assert( ...
    dt==60 && ...
    controlPeriod==300 && ...
    eventPeriod==300 && ...
    weatherPeriod==3600 && ...
    tEnd==72*3600, ...
    ['时间设置不是60 s、300 s、', ...
     '300 s、1 h和72 h。']);

t = (0:dt:tEnd)';

clock.dt = dt;
clock.t = t;
clock.nStep = numel(t);
clock.nRoom = cfg.room.nRoom;

clock.nPhysicsPerCheck = ...
    eventPeriod/dt;

clock.checkIndex = ...
    (1:clock.nPhysicsPerCheck:clock.nStep)';

%% 4. 读取并固定同一个典型72 h动态气象窗口

weatherFile = char(cfg.files.weather);

assert( ...
    isfile(weatherFile), ...
    '找不到气象文件：%s', ...
    weatherFile);

raw = readmatrix( ...
    weatherFile, ...
    'Sheet','第四部分模型输入', ...
    'Range','A2:G8761');

assert( ...
    size(raw,1)==8760 && ...
    size(raw,2)>=6, ...
    '气象表应含8760行且至少6列。');

assert( ...
    all(isfinite(raw(:,1:6)),'all'), ...
    '气象数据A:F中存在缺失值或非数值。');

allDate = datetime( ...
    raw(:,1), ...
    'ConvertFrom','excel');

allTout = raw(:,2);
allRH = raw(:,3);
allP = raw(:,5);
allCO2ppm = raw(:,6);

allWout = humidity_ratio_from_t_rh_p( ...
    allTout, ...
    allRH, ...
    allP);

[weather,selection] = select_typical_72h( ...
    allDate, ...
    allTout, ...
    allRH, ...
    allP, ...
    allCO2ppm, ...
    allWout);

hourIndex = min( ...
    floor(t/weatherPeriod)+1, ...
    72);

outdoor.T = ...
    weather.T(hourIndex);

outdoor.w = ...
    weather.w(hourIndex);

outdoor.P = ...
    weather.P(hourIndex);

outdoor.Cppm = ...
    weather.CO2ppm(hourIndex);

outdoor.c = ppm_to_mass( ...
    outdoor.Cppm, ...
    outdoor.T, ...
    outdoor.P, ...
    cfg.physical);

%% 5. 建立模型和初始状态

model = build_model(cfg,H);

initial.T = ...
    cfg.initial.T_C(:)';

initial.w = ...
    cfg.initial.w_kg_kgda(:)';

initial.Cppm = ...
    cfg.initial.CO2_ppm(:)';

fprintf('\n====================================================\n');
fprintf('每仓4台除湿器条件下的固定阈值标定开始\n');

fprintf( ...
    '理论稳定上界 thetaStab = %.15g\n', ...
    thetaStab);

fprintf( ...
    '每仓总除湿能力 = %.6f kg/h\n', ...
    cfg.device.nDehumidifier ...
    *cfg.device.dehPerUnit_kg_h);

fprintf( ...
    '候选阈值数量 = %d\n', ...
    numel(thetaCandidates));

fprintf( ...
    '气象窗口 = %s 至 %s\n', ...
    char(selection.SelectedStart), ...
    char(selection.SelectedEnd));

fprintf('====================================================\n');

%% 6. 重新运行周期通信基准

fprintf('\n正在重新运行周期通信基准……\n');

periodic = simulate_case( ...
    'Periodic', ...
    NaN, ...
    initial, ...
    model, ...
    clock, ...
    outdoor, ...
    eventNumericalTolerance);

periodic = analyze_case( ...
    periodic, ...
    model, ...
    clock);

expectedTransmissions = ...
    numel(clock.checkIndex) ...
    *clock.nRoom;

assert( ...
    periodic.metric.NetworkTransmissions ...
    ==expectedTransmissions, ...
    '周期通信发送次数与理论计数不一致。');

fprintf( ...
    '周期通信发送次数 = %d\n', ...
    periodic.metric.NetworkTransmissions);

fprintf( ...
    '周期基准安全越界样本数 = %d\n', ...
    periodic.metric.SafetyViolationSamples);

fprintf( ...
    '周期基准设备饱和次数 = %d\n', ...
    periodic.metric.SaturationAtChecks);

assert( ...
    periodic.metric.SafetyViolationSamples==0, ...
    ['4台配置下周期基准仍有安全越界，', ...
     '请检查参数是否已经保存。']);

assert( ...
    periodic.metric.SaturationAtChecks==0, ...
    ['4台配置下周期基准仍存在设备饱和，', ...
     '请先查看具体的饱和设备。']);

assert( ...
    periodic.metric.InterlockConflicts==0, ...
    '周期通信基准存在设备互锁冲突。');

%% 7. 重新运行全部固定阈值候选

nCandidate = numel(thetaCandidates);

fixedCases = cell(nCandidate,1);

for q = 1:nCandidate

    fprintf( ...
        '正在运行阈值 %2d/%2d：thetaF = %.9g……\n', ...
        q, ...
        nCandidate, ...
        thetaCandidates(q));

    oneCase = simulate_case( ...
        'Fixed', ...
        thetaCandidates(q), ...
        initial, ...
        model, ...
        clock, ...
        outdoor, ...
        eventNumericalTolerance);

    fixedCases{q} = analyze_case( ...
        oneCase, ...
        model, ...
        clock);

end

%% 8. 建立扫描结果表

ThetaFraction = thetaFraction;
ThetaF = thetaCandidates;

ThetaStab = repmat( ...
    thetaStab, ...
    nCandidate, ...
    1);

NormalizedTrackingRMSE = ...
    zeros(nCandidate,1);

TrackingDegradation_pct = ...
    zeros(nCandidate,1);

TemperatureRMSE_C = ...
    zeros(nCandidate,1);

HumidityRatioRMSE = ...
    zeros(nCandidate,1);

CO2RMSE_ppm = ...
    zeros(nCandidate,1);

NetworkTransmissions = ...
    zeros(nCandidate,1);

NetworkReceptions = ...
    zeros(nCandidate,1);

CommunicationSaving_pct = ...
    zeros(nCandidate,1);

FullControlExecutions = ...
    zeros(nCandidate,1);

ControlExecutionSaving_pct = ...
    zeros(nCandidate,1);

SafetyViolationSamples = ...
    zeros(nCandidate,1);

TemperatureViolationSamples = ...
    zeros(nCandidate,1);

HumidityViolationSamples = ...
    zeros(nCandidate,1);

CO2ViolationSamples = ...
    zeros(nCandidate,1);

SaturationAtChecks = ...
    zeros(nCandidate,1);

DehumidificationSaturationAtChecks = ...
    zeros(nCandidate,1);

InterlockConflicts = ...
    zeros(nCandidate,1);

ActiveCommunicationEnergy_J = ...
    zeros(nCandidate,1);

DeviceEnergy_kWh = ...
    zeros(nCandidate,1);

for q = 1:nCandidate

    m = fixedCases{q}.metric;

    NormalizedTrackingRMSE(q) = ...
        m.NormalizedTrackingRMSE;

    TrackingDegradation_pct(q) = ...
        100 ...
        *(m.NormalizedTrackingRMSE ...
        -periodic.metric.NormalizedTrackingRMSE) ...
        /periodic.metric.NormalizedTrackingRMSE;

    TemperatureRMSE_C(q) = ...
        m.TemperatureRMSE_C;

    HumidityRatioRMSE(q) = ...
        m.HumidityRatioRMSE;

    CO2RMSE_ppm(q) = ...
        m.CO2RMSE_ppm;

    NetworkTransmissions(q) = ...
        m.NetworkTransmissions;

    NetworkReceptions(q) = ...
        m.NetworkReceptions;

    CommunicationSaving_pct(q) = ...
        100 ...
        *(1-m.NetworkTransmissions ...
        /periodic.metric.NetworkTransmissions);

    FullControlExecutions(q) = ...
        m.FullControlExecutions;

    ControlExecutionSaving_pct(q) = ...
        100 ...
        *(1-m.FullControlExecutions ...
        /periodic.metric.FullControlExecutions);

    SafetyViolationSamples(q) = ...
        m.SafetyViolationSamples;

    TemperatureViolationSamples(q) = ...
        m.TemperatureViolationSamples;

    HumidityViolationSamples(q) = ...
        m.HumidityViolationSamples;

    CO2ViolationSamples(q) = ...
        m.CO2ViolationSamples;

    SaturationAtChecks(q) = ...
        m.SaturationAtChecks;

    DehumidificationSaturationAtChecks(q) = ...
        m.DehumidificationSaturationAtChecks;

    InterlockConflicts(q) = ...
        m.InterlockConflicts;

    ActiveCommunicationEnergy_J(q) = ...
        m.ActiveCommunicationEnergy_J;

    DeviceEnergy_kWh(q) = ...
        m.DeviceEnergy_kWh;

end

%% 9. 建立最终合格条件

WithinTrackingTolerance = ...
    TrackingDegradation_pct ...
    <=trackingTolerance_pct;

AbsoluteSafetyPass = ...
    SafetyViolationSamples==0;

NoDeviceSaturation = ...
    SaturationAtChecks==0;

NoDehumidificationSaturation = ...
    DehumidificationSaturationAtChecks==0;

NoInterlockConflict = ...
    InterlockConflicts==0;

InsideStabilityBound = ...
    ThetaF>0 ...
    & ThetaF<ThetaStab;

QualifiedForFinalUse = ...
    WithinTrackingTolerance ...
    & AbsoluteSafetyPass ...
    & NoDeviceSaturation ...
    & NoDehumidificationSaturation ...
    & NoInterlockConflict ...
    & InsideStabilityBound;

scanTable = table( ...
    ThetaFraction, ...
    ThetaF, ...
    ThetaStab, ...
    NormalizedTrackingRMSE, ...
    TrackingDegradation_pct, ...
    TemperatureRMSE_C, ...
    HumidityRatioRMSE, ...
    CO2RMSE_ppm, ...
    NetworkTransmissions, ...
    NetworkReceptions, ...
    CommunicationSaving_pct, ...
    FullControlExecutions, ...
    ControlExecutionSaving_pct, ...
    SafetyViolationSamples, ...
    TemperatureViolationSamples, ...
    HumidityViolationSamples, ...
    CO2ViolationSamples, ...
    SaturationAtChecks, ...
    DehumidificationSaturationAtChecks, ...
    InterlockConflicts, ...
    ActiveCommunicationEnergy_J, ...
    DeviceEnergy_kWh, ...
    WithinTrackingTolerance, ...
    AbsoluteSafetyPass, ...
    NoDeviceSaturation, ...
    NoDehumidificationSaturation, ...
    NoInterlockConflict, ...
    InsideStabilityBound, ...
    QualifiedForFinalUse);

%% 10. 选择最终固定阈值候选

qualifiedIndex = find( ...
    scanTable.QualifiedForFinalUse);

if isempty(qualifiedIndex)

    selectedIndex = NaN;
    thetaFinal = NaN;
    selected = struct([]);

else

    selectedIndex = choose_best_threshold( ...
        scanTable, ...
        qualifiedIndex);

    thetaFinal = ...
        scanTable.ThetaF(selectedIndex);

    selected = ...
        fixedCases{selectedIndex};

end

scanTable.FinalRecommended = ...
    false(height(scanTable),1);

if isfinite(selectedIndex)

    scanTable.FinalRecommended( ...
        selectedIndex) = true;

end

%% 11. 保存结果

writetable( ...
    scanTable, ...
    fullfile( ...
    resultDir, ...
    'fixed_threshold_scan_4units.csv'));

periodicSummary = metric_table( ...
    periodic, ...
    '周期通信');

writetable( ...
    periodicSummary, ...
    fullfile( ...
    resultDir, ...
    'periodic_baseline_4units.csv'));

weatherTable = table( ...
    (0:71)', ...
    weather.Date, ...
    weather.T, ...
    weather.RH, ...
    weather.P, ...
    weather.w, ...
    weather.CO2ppm, ...
    'VariableNames', ...
    {'HourIndex', ...
     'DateTime', ...
     'T_out_C', ...
     'RH_out_pct', ...
     'P_out_Pa', ...
     'w_out_kg_kgda', ...
     'CO2_out_ppm'});

writetable( ...
    weatherTable, ...
    fullfile( ...
    resultDir, ...
    'selected_weather_72h.csv'));

if isfinite(selectedIndex)

    finalTable = ...
        scanTable(selectedIndex,:);

    writetable( ...
        finalTable, ...
        fullfile( ...
        resultDir, ...
        'final_fixed_threshold.csv'));

    write_case_outputs( ...
        resultDir, ...
        'periodic_4units', ...
        periodic, ...
        clock, ...
        cfg, ...
        model);

    write_case_outputs( ...
        resultDir, ...
        'fixed_final_4units', ...
        selected, ...
        clock, ...
        cfg, ...
        model);

end

save( ...
    fullfile( ...
    resultDir, ...
    'fixed_threshold_calibration_4units.mat'), ...
    'cfg', ...
    'thetaStab', ...
    'thetaFraction', ...
    'thetaCandidates', ...
    'trackingTolerance_pct', ...
    'periodic', ...
