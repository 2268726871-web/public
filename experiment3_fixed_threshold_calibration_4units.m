%% ========================================================================
function result = simulate_case( ...
    mode, ...
    thetaF, ...
    initial, ...
    model, ...
    clock, ...
    outdoor, ...
    eventNumericalTolerance)

nStep = clock.nStep;
nRoom = clock.nRoom;
dt = clock.dt;

T = zeros(nStep,nRoom);
w = zeros(nStep,nRoom);
c = zeros(nStep,nRoom);

T(1,:) = initial.T;
w(1,:) = initial.w;

for i = 1:nRoom

    c(1,i) = ppm_to_mass( ...
        initial.Cppm(i), ...
        T(1,i), ...
        model.par.PIndoorRef_Pa, ...
        model.par);

end

Qraw = zeros(nStep,nRoom);
mwRaw = zeros(nStep,nRoom);
Fraw = zeros(nStep,nRoom);

Qcmd = zeros(nStep,nRoom);
mwCmd = zeros(nStep,nRoom);
Fcmd = zeros(nStep,nRoom);

satQ = false(nStep,nRoom);
satW = false(nStep,nRoom);
satF = false(nStep,nRoom);

isCheck = false(nStep,1);
isBroadcast = false(nStep,nRoom);

isFullControlExecution = ...
    false(nStep,nRoom);

eventErrorNorm = ...
    NaN(nStep,nRoom);

stateNorm = ...
    NaN(nStep,nRoom);

eventThreshold = ...
    NaN(nStep,nRoom);

zHat = zeros(nRoom,3);

hasInitialBroadcast = false;

uRawHold = zeros(nRoom,3);
uHold = zeros(nRoom,3);

satHold = false(nRoom,6);

for k = 1:nStep

    out = struct( ...
        'T',outdoor.T(k), ...
        'w',outdoor.w(k), ...
        'P',outdoor.P(k), ...
        'Cppm',outdoor.Cppm(k), ...
        'c',outdoor.c(k));

    if mod(k-1,clock.nPhysicsPerCheck)==0

        isCheck(k) = true;

        zCurrent = normalized_state( ...
            T(k,:), ...
            w(k,:), ...
            c(k,:), ...
            model);

        if ~hasInitialBroadcast

            % t=0时两组均强制发送
            trigger = true(nRoom,1);

            errorNow = zeros(nRoom,1);

            stateNow = ...
                sqrt(sum(zCurrent.^2,2));

            thresholdNow = ...
                zeros(nRoom,1);

            hasInitialBroadcast = true;

        elseif strcmpi(mode,'Periodic')

            % 周期通信：六仓全部发送
            trigger = true(nRoom,1);

            errorNow = ...
                sqrt(sum((zHat-zCurrent).^2,2));

            stateNow = ...
                sqrt(sum(zCurrent.^2,2));

            thresholdNow = ...
                zeros(nRoom,1);

        elseif strcmpi(mode,'Fixed')

            % 事件误差
            eventError = ...
                zHat-zCurrent;

            errorNow = ...
                sqrt(sum(eventError.^2,2));

            stateNow = ...
                sqrt(sum(zCurrent.^2,2));

            % 固定相对阈值
            thresholdNow = ...
                thetaF*stateNow;

            % 固定事件触发条件
            trigger = ...
                errorNow>=thresholdNow ...
                & errorNow>eventNumericalTolerance;

        else

            error('未知仿真模式：%s',mode);

        end

        % 只有触发的仓更新网络保存状态
        zHat(trigger,:) = ...
            zCurrent(trigger,:);

        isBroadcast(k,:) = ...
            trigger';

        eventErrorNorm(k,:) = ...
            errorNow';

        stateNorm(k,:) = ...
            stateNow';

        eventThreshold(k,:) = ...
            thresholdNow';

        % 本仓发送后，本仓和相邻仓控制律刷新
        affected = ...
            trigger ...
            | (model.A*double(trigger)>0);

        isFullControlExecution(k,:) = ...
            affected';

        % 根据最近发送状态计算协同控制指令
        [uRawHold,uHold,satHold] = ...
            controller_step( ...
            zHat, ...
            model, ...
            out);

    end

    Qraw(k,:) = ...
        uRawHold(:,1)';

    mwRaw(k,:) = ...
        uRawHold(:,2)';

    Fraw(k,:) = ...
        uRawHold(:,3)';

    Qcmd(k,:) = ...
        uHold(:,1)';

    mwCmd(k,:) = ...
        uHold(:,2)';

    Fcmd(k,:) = ...
        uHold(:,3)';

    satQ(k,:) = ...
        (satHold(:,1)|satHold(:,2))';

    satW(k,:) = ...
        (satHold(:,3)|satHold(:,4))';

    satF(k,:) = ...
        (satHold(:,5)|satHold(:,6))';

    if k==nStep
        break;
    end

    % 非线性守恒模型按照60 s积分
    for i = 1:nRoom

        g = model.roomStage(i);

        xk = [ ...
            T(k,i); ...
            w(k,i); ...
            c(k,i)];

        ui = uHold(i,:)';

        bio = [ ...
            model.Qbio(g); ...
            model.mbioW(g); ...
            model.mbioC(g)];

        k1 = room_rhs( ...
            xk, ...
            ui, ...
            bio, ...
            model.Mda(g), ...
            out, ...
            model.par);

        k2 = room_rhs( ...
            xk+0.5*dt*k1, ...
            ui, ...
            bio, ...
            model.Mda(g), ...
            out, ...
            model.par);

        k3 = room_rhs( ...
            xk+0.5*dt*k2, ...
            ui, ...
            bio, ...
            model.Mda(g), ...
            out, ...
            model.par);

        k4 = room_rhs( ...
            xk+dt*k3, ...
            ui, ...
            bio, ...
            model.Mda(g), ...
            out, ...
            model.par);

        xNext = ...
            xk ...
            +dt/6 ...
            *(k1+2*k2+2*k3+k4);

        T(k+1,i) = ...
            xNext(1);

        w(k+1,i) = ...
            xNext(2);

        c(k+1,i) = ...
            max(xNext(3),0);

    end
end

result.Name = mode;
result.thetaF = thetaF;

result.T = T;
result.w = w;
result.c = c;

result.Qraw = Qraw;
result.mwRaw = mwRaw;
result.Fraw = Fraw;

result.Qcmd = Qcmd;
result.mwCmd = mwCmd;
result.Fcmd = Fcmd;

result.satQ = satQ;
result.satW = satW;
result.satF = satF;

result.isCheck = isCheck;
