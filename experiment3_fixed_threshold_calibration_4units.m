function result = analyze_case(result,model,clock)

nRoom = clock.nRoom;

Cppm = mass_to_ppm( ...
    result.c, ...
    result.T, ...
    model.par.PIndoorRef_Pa, ...
    model.par);

targetT = zeros(1,nRoom);
targetW = zeros(1,nRoom);
targetC = zeros(1,nRoom);

safeTMin = zeros(1,nRoom);
safeTMax = zeros(1,nRoom);

safeWMin = zeros(1,nRoom);
safeWMax = zeros(1,nRoom);

safeCMin = zeros(1,nRoom);
safeCMax = zeros(1,nRoom);

normT = zeros(1,nRoom);
normW = zeros(1,nRoom);
normC = zeros(1,nRoom);

for i = 1:nRoom

    g = model.roomStage(i);

    targetT(i) = model.T0(g);
    targetW(i) = model.w0(g);
    targetC(i) = model.Cppm0(g);

    safeTMin(i) = model.TMin(g);
    safeTMax(i) = model.TMax(g);

    safeWMin(i) = model.wMin(g);
    safeWMax(i) = model.wMax(g);

    safeCMin(i) = model.CppmMin(g);
    safeCMax(i) = model.CppmMax(g);

    normT(i) = model.scaleT(g);
    normW(i) = model.scaleW(g);
    normC(i) = model.scaleCppm(g);

end

dT = result.T-targetT;
dW = result.w-targetW;
dC = Cppm-targetC;

zT = dT./normT;
zW = dW./normW;
zC = dC./normC;

violT = ...
    result.T<safeTMin ...
    |result.T>safeTMax;

violW = ...
    result.w<safeWMin ...
    |result.w>safeWMax;

violC = ...
    Cppm<safeCMin ...
    |Cppm>safeCMax;

anyViolation = ...
    violT ...
    |violW ...
    |violC;

[cool,heat,humid,dehumid,devicePower] = ...
    decode_devices( ...
    result.Qcmd, ...
    result.mwCmd, ...
    result.Fcmd, ...
    model.device);

interlockConflicts = ...
    nnz(cool>1e-12 & heat>1e-12) ...
    +nnz(humid>1e-12 & dehumid>1e-12);

idx = clock.checkIndex;

saturationAtChecks = ...
    nnz(result.satQ(idx,:)) ...
    +nnz(result.satW(idx,:)) ...
    +nnz(result.satF(idx,:));

dehSaturationAtChecks = ...
    nnz( ...
    result.mwRaw(idx,:) ...
    <model.limits.mwMin-1e-12);

nBroadcast = ...
    nnz(result.isBroadcast);

% 无向环形拓扑，每次发送有两个邻仓接收
nReceive = ...
    2*nBroadcast;

% 通信能耗参数沿用原通信硬件估算
activeCommunicationEnergy_J = ...
    (0.366*nBroadcast ...
    +0.310*nReceive) ...
    /1000;

deviceEnergy_kWh = ...
    sum( ...
    devicePower(1:end-1,:), ...
    'all') ...
    *clock.dt/3600;

metric.NormalizedTrackingRMSE = ...
    sqrt(mean( ...
    cat(3,zT,zW,zC).^2, ...
    'all'));

metric.TemperatureRMSE_C = ...
    sqrt(mean(dT.^2,'all'));

metric.HumidityRatioRMSE = ...
    sqrt(mean(dW.^2,'all'));

metric.CO2RMSE_ppm = ...
    sqrt(mean(dC.^2,'all'));

metric.SafetyViolationSamples = ...
    nnz(anyViolation);

metric.TemperatureViolationSamples = ...
    nnz(violT);

metric.HumidityViolationSamples = ...
    nnz(violW);

metric.CO2ViolationSamples = ...
    nnz(violC);

metric.SaturationAtChecks = ...
    saturationAtChecks;

metric.DehumidificationSaturationAtChecks = ...
    dehSaturationAtChecks;

metric.InterlockConflicts = ...
    interlockConflicts;

metric.NetworkTransmissions = ...
    nBroadcast;

metric.NetworkReceptions = ...
    nReceive;

metric.FullControlExecutions = ...
    nnz(result.isFullControlExecution);

metric.ActiveCommunicationEnergy_J = ...
    activeCommunicationEnergy_J;

metric.DeviceEnergy_kWh = ...
    deviceEnergy_kWh;

result.Cppm = Cppm;

result.dT = dT;
result.dW = dW;
result.dC = dC;

result.z = ...
    cat(3,zT,zW,zC);

result.violT = violT;
result.violW = violW;
result.violC = violC;

result.anyViolation = ...
    anyViolation;

result.devicePower_kW = ...
    devicePower;

result.metric = metric;

end

