%% ========================================================================
function [weather,selection] = select_typical_72h( ...
    date,T,RH,P,CO2ppm,w)

nHour = numel(T);

startIndex = ...
    (1:24:(nHour-72+1))';

nCandidate = ...
    numel(startIndex);

feature = ...
    zeros(nCandidate,4);

for q = 1:nCandidate

    idx = ...
        startIndex(q): ...
        (startIndex(q)+71);

    feature(q,:) = [ ...
        mean(T(idx)), ...
        mean(w(idx)), ...
        std(T(idx),1), ...
        std(w(idx),1)];

end

center = [ ...
    mean(T), ...
    mean(w), ...
    median(feature(:,3)), ...
    median(feature(:,4))];

spread = zeros(1,4);

for j = 1:4

    spread(j) = ...
        local_quantile(feature(:,j),0.75) ...
        -local_quantile(feature(:,j),0.25);

end

assert( ...
    all(spread>0), ...
    '典型72 h气象窗口筛选失败。');

score = ...
    sum(((feature-center)./spread).^2,2);

[bestScore,bestCandidate] = ...
    min(score);

idx = ...
    startIndex(bestCandidate): ...
    (startIndex(bestCandidate)+71);

weather.Date = date(idx);
weather.T = T(idx);
weather.RH = RH(idx);
weather.P = P(idx);
weather.CO2ppm = CO2ppm(idx);
weather.w = w(idx);

selection.SelectedStart = ...
    date(idx(1));

selection.SelectedEnd = ...
    date(idx(end));

selection.Score = ...
    bestScore;

end

%% ========================================================================
function q = local_quantile(x,p)

x = sort(x(:));

position = ...
    1+(numel(x)-1)*p;

lo = floor(position);
hi = ceil(position);

q = ...
    x(lo) ...
    +(x(hi)-x(lo)) ...
    *(position-lo);

end

