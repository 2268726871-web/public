function cfg = mushroom_system_parameters()
%MUSHROOM_SYSTEM_PARAMETERS 多蘑菇仓研究的唯一参数入口
%
% 数据性质标记：
%   [I] 继承值：来自现有模型、数据表、用户要求或设备资料
%   [D] 派生值：由程序根据基础参数计算
%   [A] 算法设计值：控制器、拓扑、时间尺度等人为设计参数
%   [P] 待定值：必须通过后续核对或参数校准确定
%
% 使用方法：
%   cfg = mushroom_system_parameters();
%
% 重要原则：
%   1. 后续程序只读取cfg，不再重复手填参数；
%   2. 平衡输入必须在本函数中重新计算全精度值；
%   3. 不保存显示位数截断后的A、B、H、Ad、Bd矩阵；
%   4. 待校准参数使用NaN，防止在未确定前被误用。

%% 1. 仿真时间设置
cfg.time.dt_s = 60;                    % [A] 非线性模型积分步长
cfg.time.controlPeriod_s = 300;       % [A] 控制指令更新周期
cfg.time.eventCheckPeriod_s = 300;    % [A] 事件触发检查周期
cfg.time.weatherPeriod_s = 3600;      % [A] 气象更新周期
cfg.time.mainDuration_s = 72*3600;    % [A] 主场景72 h
cfg.time.equilibriumDuration_s = 24*3600; % [A] 平衡验证24 h

cfg.time.nPhysicsPerControl = ...
    cfg.time.controlPeriod_s / cfg.time.dt_s;

%% 2. 物理常数和仓体参数
cfg.physical.rhoAir_kg_m3 = 1.2;       % [I] 湿空气密度
cfg.physical.cpAir_J_kgK = 1006;       % [I] 空气定压比热
cfg.physical.UA_W_K = 31.5;            % [I] 围护结构综合传热参数
cfg.physical.CT_J_K = 6.85e6;          % [I] 仓体等效热容量
cfg.physical.V_m3 = 104;               % [I] 仓内容积

cfg.physical.R_J_molK = 8.314462618;   % [I] 通用气体常数
cfg.physical.MCO2_kg_mol = 44.01e-3;   % [I] CO2摩尔质量
cfg.physical.PIndoorRef_Pa = 101325;   % [I] 室内ppm换算参考压力

%% 3. 标称室外状态
cfg.outdoor.nominal.T_C = 22.34160274;       % [D] 南宁2023全年平均
cfg.outdoor.nominal.w_kg_kgda = ...
    0.0146041409999;                         % [D] 全年平均含湿量
cfg.outdoor.nominal.P_Pa = 99249.5605;       % [D] 全年平均气压
cfg.outdoor.nominal.CO2_ppm = 419.35;        % [I] 2023背景代理值

% [D] 室外CO2质量浓度
cfg.outdoor.nominal.cCO2_kg_m3 = ppm_to_mass_local( ...
    cfg.outdoor.nominal.CO2_ppm, ...
    cfg.outdoor.nominal.T_C, ...
    cfg.outdoor.nominal.P_Pa, ...
    cfg.physical);

%% 4. 四阶段名称
cfg.stage.names = {'G1'; 'G2'; 'G3'; 'G4'};
cfg.stage.nStage = 4;

%% 5. 四阶段目标状态
cfg.stage.TTarget_C = [23; 24; 16; 16];                 % [I]
cfg.stage.wTarget_kg_kgda = ...
    [0.0168318; 0.0179081; 0.0096345; 0.0096345];      % [I]
cfg.stage.CO2Target_ppm = [12500; 12500; 900; 900];     % [I]
cfg.stage.Mda_kg = [120.7; 120.1; 125.0; 125.0];        % [I]

% [D] 目标CO2由ppm转换为质量浓度
cfg.stage.cCO2Target_kg_m3 = zeros(cfg.stage.nStage,1);

for g = 1:cfg.stage.nStage
    cfg.stage.cCO2Target_kg_m3(g) = ppm_to_mass_local( ...
        cfg.stage.CO2Target_ppm(g), ...
        cfg.stage.TTarget_C(g), ...
        cfg.physical.PIndoorRef_Pa, ...
        cfg.physical);
end

%% 6. 四阶段生物源项
cfg.bio.Q_W = [170; 246; 246; 189];                 % [I] 生物热源
