    [0.0149619; 0.0159232; 0.0084889; 0.0084889];    % [D]
cfg.safety.wMax_kg_kgda = ...
    [0.0179081; 0.0190463; 0.0108933; 0.0108933];    % [D]

cfg.safety.CO2Min_ppm = [10000; 10000; 800; 800];    % [I]
