%% 17. 自适应事件触发参数
% 尚未完成标定的参数必须使用NaN，禁止提前给出数值。

cfg.adaptive.Q = NaN(3,3);                   % [P] 状态权重矩阵
cfg.adaptive.thetaMin = NaN;                 % [P] 动态阈值下限
