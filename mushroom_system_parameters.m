function c = ppm_to_mass_local(Cppm,TdegC,pressurePa,physical)
%PPM_TO_MASS_LOCAL ppm转换为CO2质量浓度kg/m^3

c = Cppm .* 1e-6 .* pressurePa .* ...
    physical.MCO2_kg_mol ./ ...
    (physical.R_J_molK .* (TdegC+273.15));

end


function validate_configuration(cfg)
%VALIDATE_CONFIGURATION 检查参数入口内部是否自洽

% 时间周期检查
assert(mod(cfg.time.controlPeriod_s,cfg.time.dt_s)==0, ...
    '控制周期必须是积分步长的整数倍。');

assert(mod(cfg.time.eventCheckPeriod_s,cfg.time.dt_s)==0, ...
    '事件检查周期必须是积分步长的整数倍。');

assert(mod(cfg.time.weatherPeriod_s,cfg.time.dt_s)==0, ...
    '气象周期必须是积分步长的整数倍。');

% 阶段配置检查
assert(numel(cfg.room.stageIndex)==cfg.room.nRoom, ...
    '六仓阶段配置长度错误。');

assert(all(cfg.room.stageIndex>=1 & ...
           cfg.room.stageIndex<=cfg.stage.nStage), ...
    '六仓阶段编号越界。');

% 目标必须位于安全范围内
assert(all(cfg.stage.TTarget_C>=cfg.safety.TMin_C & ...
           cfg.stage.TTarget_C<=cfg.safety.TMax_C), ...
    '阶段目标温度不在安全范围内。');

assert(all(cfg.stage.wTarget_kg_kgda>= ...
           cfg.safety.wMin_kg_kgda & ...
           cfg.stage.wTarget_kg_kgda<= ...
           cfg.safety.wMax_kg_kgda), ...
    '阶段目标含湿量不在安全范围内。');

assert(all(cfg.stage.CO2Target_ppm>= ...
           cfg.safety.CO2Min_ppm & ...
           cfg.stage.CO2Target_ppm<= ...
           cfg.safety.CO2Max_ppm), ...
    '阶段目标CO2不在安全范围内。');

% 归一化尺度必须为正
assert(all(cfg.normalization.scaleT_C>0), ...
    '温度归一化尺度必须大于0。');

assert(all(cfg.normalization.scaleW_kg_kgda>0), ...
    '含湿量归一化尺度必须大于0。');

assert(all(cfg.normalization.scaleCO2_ppm>0), ...
    'CO2归一化尺度必须大于0。');

% 强制检查2号仓初始含湿量
assert(abs(cfg.initial.w_kg_kgda(2)-0.0165089) < 1e-12, ...
    '2号仓初始含湿量必须为0.0165089。');

% 环形拓扑检查
assert(isequal(cfg.network.A,cfg.network.A'), ...
    '邻接矩阵必须为对称矩阵。');

assert(all(cfg.network.nNeighbor==2), ...
    '六仓环形拓扑中每个仓应有两个邻居。');

% 平衡输入必须为有限数
assert(all(isfinite(cfg.equilibrium.u0),'all'), ...
    '全精度平衡输入中存在无效数值。');

end