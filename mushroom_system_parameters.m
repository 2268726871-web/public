% 安全预警裕量尚未最终确定
cfg.safety.warningMarginFraction = NaN;              % [P]

%% 8. 归一化尺度
% 采用“目标到上下安全边界的较小距离”作为归一化尺度。
% 全部由目标和安全范围自动计算，不再手工填写。

cfg.normalization.scaleT_C = min( ...
    [cfg.stage.TTarget_C-cfg.safety.TMin_C, ...
     cfg.safety.TMax_C-cfg.stage.TTarget_C], [], 2);

cfg.normalization.scaleW_kg_kgda = min( ...
    [cfg.stage.wTarget_kg_kgda-cfg.safety.wMin_kg_kgda, ...
     cfg.safety.wMax_kg_kgda-cfg.stage.wTarget_kg_kgda], [], 2);

cfg.normalization.scaleCO2_ppm = min( ...
    [cfg.stage.CO2Target_ppm-cfg.safety.CO2Min_ppm, ...
     cfg.safety.CO2Max_ppm-cfg.stage.CO2Target_ppm], [], 2);

%% 9. 全精度四阶段平衡输入
% CO2平衡：
%   0 = F0*(cout-c0) + mbioCO2

cfg.equilibrium.F0_m3_s = ...
    cfg.bio.mCO2_kg_s ./ ...
    (cfg.stage.cCO2Target_kg_m3 - ...
     cfg.outdoor.nominal.cCO2_kg_m3);

% 水分平衡：
%   0 = rho*F0*(wout-w0) + mw0 + mbioW

cfg.equilibrium.mWater0_kg_s = ...
    cfg.physical.rhoAir_kg_m3 .* ...
    cfg.equilibrium.F0_m3_s .* ...
    (cfg.stage.wTarget_kg_kgda - ...
     cfg.outdoor.nominal.w_kg_kgda) ...
    - cfg.bio.mWater_kg_s;

% 温度平衡：
%   0 = UA*(Tout-T0)
%       + rho*cp*F0*(Tout-T0)
%       + Q0 + Qbio

cfg.equilibrium.Q0_W = ...
    (cfg.physical.UA_W_K ...
     + cfg.physical.rhoAir_kg_m3 .* ...
       cfg.physical.cpAir_J_kgK .* ...
       cfg.equilibrium.F0_m3_s) ...
    .* (cfg.stage.TTarget_C - ...
        cfg.outdoor.nominal.T_C) ...
    - cfg.bio.Q_W;

% 四阶段全精度平衡输入矩阵，每一行对应一个阶段
cfg.equilibrium.u0 = [ ...
    cfg.equilibrium.Q0_W, ...
    cfg.equilibrium.mWater0_kg_s, ...
    cfg.equilibrium.F0_m3_s];

%% 10. 平衡方程残差
% 残差只用于数值核对，不参与控制。

cfg.audit.balanceResidual = zeros(cfg.stage.nStage,3);

for g = 1:cfg.stage.nStage
    F0 = cfg.equilibrium.F0_m3_s(g);
    Q0 = cfg.equilibrium.Q0_W(g);
    mw0 = cfg.equilibrium.mWater0_kg_s(g);

    residualT = ...
        cfg.physical.UA_W_K * ...
        (cfg.outdoor.nominal.T_C-cfg.stage.TTarget_C(g)) ...
        + cfg.physical.rhoAir_kg_m3 * ...
          cfg.physical.cpAir_J_kgK * F0 * ...
          (cfg.outdoor.nominal.T_C-cfg.stage.TTarget_C(g)) ...
        + Q0 + cfg.bio.Q_W(g);

    residualW = ...
        cfg.physical.rhoAir_kg_m3 * F0 * ...
        (cfg.outdoor.nominal.w_kg_kgda ...
         - cfg.stage.wTarget_kg_kgda(g)) ...
        + mw0 + cfg.bio.mWater_kg_s(g);

    residualC = ...
        F0 * ...
        (cfg.outdoor.nominal.cCO2_kg_m3 ...
         - cfg.stage.cCO2Target_kg_m3(g)) ...
        + cfg.bio.mCO2_kg_s(g);

    cfg.audit.balanceResidual(g,:) = ...
        [residualT, residualW, residualC];
end

%% 11. 六仓配置
cfg.room.nRoom = 6;

cfg.room.names = { ...
    '1号仓'; '2号仓'; '3号仓'; ...
    '4号仓'; '5号仓'; '6号仓'};

% 1、2号仓为G1；3号仓为G2；
% 4、5号仓为G3；6号仓为G4。
cfg.room.stageIndex = [1; 1; 2; 3; 3; 4];
cfg.room.stageName = cfg.stage.names(cfg.room.stageIndex);

%% 12. 六仓控制实验初始状态
cfg.initial.T_C = ...
