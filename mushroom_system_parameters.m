    [7.87e-5; 8.36e-5; 1.53e-4; 1.53e-4];          % [I] 生物水分源
cfg.bio.mCO2_kg_s = ...
    [4.73e-5; 6.83e-5; 6.83e-5; 5.25e-5];          % [I] 生物CO2源

%% 7. 四阶段环境安全范围
